#!/usr/bin/env node
/**
 * build-dist.mjs — builds dist/, the folder that goes on the web server.
 *
 *   index.html       loads one stylesheet and one script, each with a version in the URL
 *   style.css
 *   app.bundle.js    stories, audio timings and app code in one file (fewer requests)
 *   audio/*.mp3
 *   .htaccess        tells browsers to cache audio, script and stylesheet for a long time
 *
 * Long caching is safe because every cached URL carries a version (?v=…) that changes
 * with the file's content; index.html itself is always re-checked.
 *
 * Upload the CONTENTS of dist/ (including the hidden .htaccess). Nothing else belongs
 * on the server, especially not .env or tools/.
 *
 * Usage: node tools/build-dist.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const version = (text) => crypto.createHash('sha1').update(text).digest('hex').slice(0, 8);

fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(path.join(DIST, 'audio'), { recursive: true });

// 1. one script: every <script src> of index.html, in order
let html = read('index.html');
const scripts = [...html.matchAll(/<script src="([^"]+)"><\/script>\n?/g)];
if (!scripts.length) throw new Error('No <script src> tags found in index.html');
const bundle = scripts.map((m) => `/* ${m[1]} */\n${read(m[1])}`).join('\n;\n');
fs.writeFileSync(path.join(DIST, 'app.bundle.js'), bundle);

// 2. stylesheet
const css = read('style.css');
fs.writeFileSync(path.join(DIST, 'style.css'), css);

// 3. index.html pointing at the versioned files
scripts.forEach((m, i) => { html = html.replace(m[0], i === 0 ? `<script src="app.bundle.js?v=${version(bundle)}"></script>\n` : ''); });
if (!html.includes('href="style.css"')) throw new Error('style.css link not found in index.html');
html = html.replace('href="style.css"', `href="style.css?v=${version(css)}"`);
fs.writeFileSync(path.join(DIST, 'index.html'), html);

// 4. audio
let mp3 = 0;
for (const f of fs.readdirSync(path.join(ROOT, 'audio'))) {
  if (!f.endsWith('.mp3')) continue;
  fs.copyFileSync(path.join(ROOT, 'audio', f), path.join(DIST, 'audio', f));
  mp3++;
}

// 5. caching rules for Apache (Hostpoint)
fs.writeFileSync(path.join(DIST, '.htaccess'), `# Generated by tools/build-dist.mjs
# Audio, script and stylesheet URLs carry a version (?v=...), so browsers may keep them for a year.
# index.html is always re-checked, so updates show up immediately.
<IfModule mod_headers.c>
  <FilesMatch "\\.(mp3|js|css)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType audio/mpeg "access plus 1 year"
  ExpiresByType text/javascript "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType text/html "access plus 0 seconds"
</IfModule>
`);

let bytes = 0;
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p); else bytes += fs.statSync(p).size;
  }
})(DIST);
console.log(`dist/ is ready: index.html, style.css, app.bundle.js, .htaccess and ${mp3} MP3s (${(bytes / 1024 / 1024).toFixed(1)} MB)`);
